'use client';

import { Flame, Footprints, Heart, HeartPulse, Info } from 'lucide-react';
import api from '../api';
import useFetch from '../hooks/useFetch';
import { RANGE_OPTIONS, usePageControls } from '../context/PageControlsContext';
import PageHeader from '../components/PageHeader';
import MetricCard from '../components/MetricCard';
import ChartCard, { SIMULATED_NOTE } from '../components/charts/ChartCard';
import HeartRateChart from '../components/charts/HeartRateChart';
import DailyBarChart from '../components/charts/DailyBarChart';
import StateBreakdownChart from '../components/charts/StateBreakdownChart';
import { fmtNumber } from '../utils/format';

export default function Analytics() {
    const { range, refreshKey } = usePageControls();
    const rangeLabel = RANGE_OPTIONS.find((r) => r.value === range)?.label.toLowerCase();
    const days = range === '30d' ? 30 : 7;

    const readings = useFetch(async () => (await api.get('/activity/readings', { params: { range } })).data, [range, refreshKey], { intervalMs: 30000 });
    const daily = useFetch(async () => (await api.get('/activity/daily', { params: { days } })).data, [days, refreshKey], { intervalMs: 30000 });

    const r = readings.data;
    const s = r?.summary;
    const noReadings = r && r.summary.readings === 0;
    const hasStates = r && Object.keys(r.states).length > 0;
    const dailyEmpty = daily.data && !daily.data.some((x) => x.has_data);

    return (
        <>
            <PageHeader
                title="Activity analytics"
                description="Heart rate, steps and calories over time. Change the period from the selector above."
            />

            <div className="mb-5 flex items-start gap-2.5 rounded-lg border border-line bg-surface px-4 py-3 text-[13px] text-text-soft">
                <Info size={16} className="mt-0.5 shrink-0 text-text-muted" aria-hidden="true" />
                <p>All activity measurements on this page are generated by a simulated wearable, not a real device.</p>
            </div>

            <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
                <MetricCard icon={Heart} tone="coral" label="Average heart rate" loading={readings.loading}
                    value={s?.avg_heart_rate ?? '–'} unit={s?.avg_heart_rate ? 'bpm' : undefined} support={rangeLabel} />
                <MetricCard icon={HeartPulse} tone="coral" label="Heart-rate range" loading={readings.loading}
                    value={s?.min_heart_rate != null ? `${s.min_heart_rate}–${s.max_heart_rate}` : '–'} unit={s?.min_heart_rate != null ? 'bpm' : undefined} support="Lowest to highest reading" />
                <MetricCard icon={Footprints} tone="emerald" label="Steps" loading={readings.loading}
                    value={fmtNumber(s?.steps ?? 0)} support={rangeLabel} />
                <MetricCard icon={Flame} tone="amber" label="Estimated calories burned" loading={readings.loading}
                    value={fmtNumber(s?.calories ?? 0)} unit="kcal" support={rangeLabel} />
            </div>

            <div className="mt-4">
                <ChartCard
                    title="Heart-rate trend"
                    subtitle={r ? `Average bpm per ${r.bucket_minutes >= 60 ? `${r.bucket_minutes / 60} h` : `${r.bucket_minutes} min`} · ${rangeLabel}` : rangeLabel}
                    note={SIMULATED_NOTE}
                    height={320}
                    loading={readings.loading} error={readings.error} onRetry={readings.reload}
                    empty={noReadings}
                >
                    {r && <HeartRateChart points={r.points} range={range} />}
                </ChartCard>
                {r?.truncated && (
                    <p className="mt-2 text-xs text-text-muted">This period has a very large number of readings, so only the most recent ones are included.</p>
                )}
            </div>

            <div className="mt-4 grid gap-4 lg:grid-cols-2">
                <ChartCard title="Steps per day" subtitle={`Last ${days} days`} note={SIMULATED_NOTE}
                    loading={daily.loading} error={daily.error} onRetry={daily.reload} empty={dailyEmpty}
                    emptyDescription="No daily activity has been recorded in this period.">
                    {daily.data && <DailyBarChart days={daily.data} metric="steps" />}
                </ChartCard>
                <ChartCard title="Estimated calories per day" subtitle={`Last ${days} days`} note={SIMULATED_NOTE}
                    loading={daily.loading} error={daily.error} onRetry={daily.reload} empty={dailyEmpty}
                    emptyDescription="No daily activity has been recorded in this period.">
                    {daily.data && <DailyBarChart days={daily.data} metric="calories" />}
                </ChartCard>
            </div>

            <div className="mt-4">
                <ChartCard title="Activity breakdown" subtitle={`Share of readings by activity state · ${rangeLabel}`} note={SIMULATED_NOTE}
                    height={220} loading={readings.loading} error={readings.error} onRetry={readings.reload} empty={!hasStates}>
                    {hasStates && <StateBreakdownChart states={r.states} />}
                </ChartCard>
            </div>
        </>
    );
}
